// Builds tailwind-data.js from the installed Tailwind v4 package and this repo's theme:
//   preflight     — TSX styles are diffed against Tailwind's reset, not browser defaults
//   palette       — default colors as sRGB hex
//   theme         — Tailwind's theme variables, overridden by @theme blocks in packages/ui
//   rootVars      — the project's :root tokens (--primary, --radius…), light theme
//   customVariants— @custom-variant names (dark…)
// Run: node scripts/build-tailwind-data.mjs [path/to/tailwindcss]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, "..")
const repo = join(root, "..", "..")

function findTailwind() {
  if (process.argv[2]) return process.argv[2]
  const pnpm = join(repo, "node_modules", ".pnpm")
  const dir = existsSync(pnpm) && readdirSync(pnpm).filter((d) => /^tailwindcss@4/.test(d)).sort().pop()
  if (dir) return join(pnpm, dir, "node_modules", "tailwindcss")
  const flat = join(repo, "node_modules", "tailwindcss")
  if (existsSync(flat)) return flat
  throw new Error("tailwindcss v4 not found — pass its path as the first argument")
}

const tw = findTailwind()
const version = JSON.parse(readFileSync(join(tw, "package.json"), "utf8")).version

// --theme(--x, fallback) only works inside Tailwind's compiler; keep the fallback.
const preflight = readFileSync(join(tw, "preflight.css"), "utf8")
  .replace(/\/\*[\s\S]*?\*\//g, "")
  .replace(/--theme\(\s*--[\w-]+\s*,\s*([\s\S]*?)\)\s*;/g, "$1;")
  .replace(/\n\s*\n/g, "\n")
  .trim()

function oklchToHex(L, C, H) {
  const h = (H * Math.PI) / 180
  const a = C * Math.cos(h), b = C * Math.sin(h)
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ]
  return "#" + lin
    .map((c) => {
      const v = c <= 0.0031308 ? 12.92 * c : 1.055 * Math.pow(c, 1 / 2.4) - 0.055
      return Math.round(Math.max(0, Math.min(1, v)) * 255).toString(16).padStart(2, "0")
    })
    .join("")
}

const themeCss = readFileSync(join(tw, "theme.css"), "utf8")
const palette = { white: "#ffffff", black: "#000000" }
for (const m of themeCss.matchAll(/--color-([a-z]+-\d+):\s*oklch\(([\d.]+)%\s+([\d.]+)\s+([\d.]+)\)/g)) {
  palette[m[1]] = oklchToHex(+m[2] / 100, +m[3], +m[4])
}

const theme = {}
const readThemeVars = (css) => {
  for (const block of [...css.matchAll(/@theme[^{]*\{([\s\S]*?)\n\}/g)].map((m) => m[1])) {
    for (const m of block.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) theme[m[1]] = m[2].replace(/\s+/g, " ").trim()
  }
}
readThemeVars(themeCss)
const projectStyles = join(repo, "packages", "ui", "src", "styles")
const styleFiles = existsSync(projectStyles) ? readdirSync(projectStyles).filter((f) => f.endsWith(".css")) : []
for (const f of styleFiles) readThemeVars(readFileSync(join(projectStyles, f), "utf8"))

const rootVars = {}
const globalsCss = join(projectStyles, "globals.css")
if (existsSync(globalsCss)) {
  const m = /(^|\n):root\s*\{([\s\S]*?)\n\}/.exec(readFileSync(globalsCss, "utf8"))
  if (m) for (const d of m[2].matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)) rootVars[d[1]] = d[2].replace(/\s+/g, " ").trim()
}

const customVariants = []
for (const f of styleFiles) {
  for (const m of readFileSync(join(projectStyles, f), "utf8").matchAll(/@custom-variant\s+([\w-]+)/g)) customVariants.push(m[1])
}

writeFileSync(
  join(root, "tailwind-data.js"),
  `// Generated by scripts/build-tailwind-data.mjs from tailwindcss@${version} + packages/ui. Do not edit.\nglobalThis.__copycodeTW = ${JSON.stringify({ version, preflight, palette, theme, rootVars, customVariants })}\n`
)
console.log(`tailwind-data.js — tailwindcss@${version}, ${Object.keys(palette).length} colors, ${Object.keys(theme).length} theme vars, ${Object.keys(rootVars).length} root vars`)
