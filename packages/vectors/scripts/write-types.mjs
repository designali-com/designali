// Writes dist/types.d.ts: small declarations for every export of
// src/generated/index.tsx and src/generated/all.tsx.
//
// Type-checking the thousands of generated .tsx sources needs more than 2 GB
// of memory and crashes `tsc`. Apps type-check against this file instead
// (see apps/web/tsconfig.typecheck.json). It is a .d.ts, so `skipLibCheck`
// skips it, and every component shares one type.
import { promises as fs } from "node:fs"
import path from "node:path"

export async function writeTypes(root) {
  const gen = path.join(root, "src/generated")
  const index = await fs.readFile(path.join(gen, "index.tsx"), "utf8")
  const all = await fs.readFile(path.join(gen, "all.tsx"), "utf8")

  // Props: copy the body of the first generated Props interface. All
  // components in a package share the same props.
  const firstFile = index.match(/export \{[^}]*\} from '(\.\/[^']+)'/g)
    ?.map((l) => l.match(/from '([^']+)'/)[1])
    .find((p) => p !== "./all")
  const firstSrc = await fs.readFile(path.join(gen, `${firstFile}.tsx`), "utf8")
  const propsBody = firstSrc.match(
    /export interface \w+Props extends React\.SVGProps<SVGSVGElement> \{([^}]*)\}/
  )?.[1]
  if (propsBody === undefined) {
    throw new Error(`Could not read the props interface from ${firstFile}.tsx`)
  }

  const out = [
    "/** Auto-generated by scripts/write-types.mjs - Do not edit */",
    'import type * as React from "react";',
    "",
    "export interface SvgComponentProps extends React.SVGProps<SVGSVGElement> {",
    ...propsBody
      .split("\n")
      .map((l) => l.trim())
      .filter(Boolean)
      .map((l) => `  ${l}`),
    "}",
    "export type SvgComponent = React.ForwardRefExoticComponent<",
    '  Omit<SvgComponentProps, "ref"> & React.RefAttributes<SVGSVGElement>',
    ">;",
    "export interface SvgMetadata {",
    "  readonly id: string;",
    "  readonly baseId: string;",
    "  readonly variant: string;",
    "  readonly name: string;",
    "  readonly category: string;",
    "  readonly tags: readonly string[] | undefined;",
    "  readonly viewBox: string;",
    "}",
    "",
  ]

  // allIcons / allLogos / allVectors
  const allMatch = all.match(/export const (\w+)(?:\s*:\s*([^=]+))?\s*=\s*\{/)
  if (!allMatch) throw new Error("Could not find the export in all.tsx")
  const [, allName, allType] = allMatch
  const entryInterface = all.match(/export interface LogoEntry \{[\s\S]*?\n\}/)
  if (entryInterface) out.push(entryInterface[0], "")

  if (allType) {
    out.push(`export declare const ${allName}: ${allType.trim()};`)
  } else {
    // Keep the exact category and component keys of the object literal.
    const body = all.slice(allMatch.index + allMatch[0].length)
    out.push(`export declare const ${allName}: {`)
    for (const line of body.split("\n")) {
      const cat = line.match(/^ {2}(["\w-]+): \{\s*$/)
      const item = line.match(/^ {4}(["\w-]+): \{ Component:/)
      if (cat) out.push(`  ${cat[1]}: {`)
      else if (item)
        out.push(`    ${item[1]}: { Component: SvgComponent; metadata: SvgMetadata };`)
      else if (/^ {2}\},?\s*$/.test(line)) out.push("  };")
      else if (/^\};?\s*$/.test(line)) break
    }
    out.push("};")
  }
  out.push("")

  // Named component exports.
  for (const m of index.matchAll(/^export \{ ([^}]+) \} from '([^']+)';$/gm)) {
    if (m[2] === "./all") continue
    for (const raw of m[1].split(",")) {
      const name = raw.trim()
      if (!name) continue
      if (name.startsWith("type ")) {
        out.push(`export type ${name.slice(5).trim()} = SvgComponentProps;`)
      } else if (name.endsWith("Metadata")) {
        out.push(`export declare const ${name}: SvgMetadata;`)
      } else {
        out.push(`export declare const ${name}: SvgComponent;`)
      }
    }
  }

  const outfile = path.join(root, "dist/types.d.ts")
  await fs.mkdir(path.dirname(outfile), { recursive: true })
  await fs.writeFile(outfile, out.join("\n") + "\n")
  return outfile
}
